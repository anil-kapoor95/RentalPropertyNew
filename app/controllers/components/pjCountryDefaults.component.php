	/** Currency code of the country (null when unknown). */
	public static function currency($alpha_2)
	{
		$a = strtoupper((string) $alpha_2);
		return isset(self::$map[$a]) ? self::$map[$a][0] : null;
	}

	/** Time zones of the country this PHP knows (Region/City). */
	public static function timezones($alpha_2)
	{
		$a = strtoupper((string) $alpha_2);
		if (!preg_match('/^[A-Z]{2}$/', $a))
		{
			return array();
		}
		$list = @DateTimeZone::listIdentifiers(DateTimeZone::PER_COUNTRY, $a);
		return is_array($list) ? array_values($list) : array();
	}

	/** Main time zone of the country (null when unknown). */
	public static function timezone($alpha_2)
	{
		$a = strtoupper((string) $alpha_2);
		$zones = self::timezones($a);
		if (isset(self::$map[$a]) && self::$map[$a][1] !== null && (empty($zones) || in_array(self::$map[$a][1], $zones, true)))
		{
			return self::$map[$a][1];
		}
		return !empty($zones) ? $zones[0] : null;
	}
